/**
 * レシートの品目などのカテゴリを AI に決めてもらうときの判断基準（2026-11-02 改善要望: スーパーA のレシートで、冷凍の炒飯・
 * うどん・パン・納豆まで中食になった。カテゴリの名前だけでは「中食」と「食料品」の境目が伝わらない）。
 * 利用者のカテゴリにある名前の分だけを渡す。自動入力のルール（設定）に書いたことのほうを優先させる
 */
const GUIDE: Record<string, string> = {
  '食料品': '家で調理・加工して食べる食材（肉・魚・野菜・果物・米・麺・パン・卵・豆腐・納豆・牛乳・調味料など）と、冷凍食品・レトルト・カップ麺・インスタント食品など保存して後で食べるもの',
  '中食': '買ってそのまま食べる、店で調理済みの弁当・丼・惣菜（コロッケ・揚げ物・焼き鳥など）・おにぎり・サンドイッチ・調理パン・サラダ',
  '外食': '飲食店の店内で食べた・店から出前を取った食事代',
  '間食': 'お菓子・スナック・アイス・デザート・甘い物・ジュースなどの飲み物・カフェでの飲食',
  '日用品': '洗剤・ティッシュ・トイレットペーパー・ゴミ袋・電池・文房具など、食べ物以外の消耗品（レジ袋は含めない）',
};

/** 小分類の名前（「食費 / 中食」なら「中食」）で引く */
const leaf = (label: string) => label.split(' / ').at(-1) ?? label;

/** カテゴリの判断基準の行（利用者のカテゴリにあるものだけ。なければ空） */
export function categoryGuideLines(labels: readonly string[]): string[] {
  const lines = labels.filter((l) => GUIDE[leaf(l)]).map((l) => `- ${l}: ${GUIDE[leaf(l)]}`);
  return lines.length === 0 ? [] : ['# カテゴリの判断基準（品目ごとに、品名から当てはまるものを選ぶ）', ...lines];
}
