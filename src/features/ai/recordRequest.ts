/**
 * AI 相談で「記録して」と頼まれたときの受け渡し（2026-11-24 ユーザーの要望）。
 * AI は記録を下の決まった形のコードの囲み（言語名 kakeibo-record）で返し、アプリはそれを見つけたら「入力」に移って、
 * 囲みの中の文を AI入力の文の欄に入れて読み取る（保存は確認の一覧でユーザーがする）
 */
export const RECORD_BLOCK = 'kakeibo-record';

/** AI 相談の指示に足す、記録の頼み方の決まり */
export const RECORD_PROMPT = `# 記録を頼まれたとき
ユーザーが「記録して」「入れておいて」「家計簿につけて」など、記録を作ることを頼んだら、答えの最後に次の形のコードの囲み（言語名 ${RECORD_BLOCK}）を1つだけ書いてください。アプリがこれを読み取って、AI入力の確認の一覧に出します（保存はユーザーが確かめてからするので、「記録しました」とは言わず、「入力の画面で確かめて保存してください」と伝える）。
\`\`\`${RECORD_BLOCK}
1. 2026-11-16 振替 2,000円 出金元の口座 → 入金先の口座 内容: NISA へ積み立て
2. 2026-11-20 支払い 1,280円 出金元の口座 内容: スーパー カテゴリ: 食費 / 食料品 メモ: まとめ買い
3. 2026-11-25 収入 50,000円 → 入金先の口座 内容: 仕送り
\`\`\`
- 1行に1件。日付（YYYY-MM-DD）・種類（支払い・収入・振替のどれか）・金額（円）・口座・内容の順。カテゴリ・メモは分かるときだけ
- 口座は「家計の材料」の口座の名前をそのまま使う。分からない・候補が2つ以上あるときは「?」と書く（「AまたはB」のようにしない）
- 支払いは出金元だけ、収入は入金先だけ（「→ 入金先」）、振替は「出金元 → 入金先」
- 添えられた画像（レシート・明細など）から記録を頼まれたら、画像から読み取った記録をこの形で書く
- 記録を頼まれていないときは、この囲みを書かない`;

/** 返事から記録の囲みの中身を取り出す。なければ null */
export function extractRecordRequest(reply: string): string | null {
  const match = new RegExp(`\`\`\`${RECORD_BLOCK}[^\\n]*\\n([\\s\\S]*?)\`\`\``).exec(reply);
  const body = match?.[1].trim();
  return body ? body : null;
}
