/** 用語の説明をまとめて1つの文にする（AI 相談に渡す） */
export function appGuideText(): string {
  const lines = (title: string, terms: Term[]) => [`## ${title}`, ...terms.map((t) => `- ${t.term}: ${t.description}`)];
  return [
    '## 画面',
    SCREEN_GUIDE,
    ...lines('残高', BALANCE_TERMS),
    ...lines(
      '口座の種類',
      (Object.keys(ACCOUNT_DESCRIPTIONS) as AccountKind[]).map((k) => ({
        term: ACCOUNT_KIND_INFO[k].label,
        description: ACCOUNT_DESCRIPTIONS[k],
      })),
    ),
    ...lines(
      '記録の種類',
      (Object.keys(TYPE_DESCRIPTIONS) as TransactionType[]).map((t) => ({
        term: TRANSACTION_RULES[t].label,
        description: TYPE_DESCRIPTIONS[t],
      })),
    ),
    ...lines('そのほか', OTHER_TERMS),
  ].join('\n');
}
